using System.Collections.Generic;
using System.Linq;
using System.Text;
using System.Threading;
using CommonConfigGen;
using Microsoft.CodeAnalysis;
using Microsoft.CodeAnalysis.CSharp;
using Microsoft.CodeAnalysis.CSharp.Syntax;
using Microsoft.CodeAnalysis.Text;

namespace CommonConfigGen.Generator
{
    [Microsoft.CodeAnalysis.Generator]
    public class GetterGenerator : IIncrementalGenerator
    {
        private const string ScriptableObjectFqn = "UnityEngine.ScriptableObject";

        public void Initialize(IncrementalGeneratorInitializationContext context)
        {
            IncrementalValuesProvider<(TypeDeclarationSyntax Syntax, INamedTypeSymbol Symbol)> targets =
                context.SyntaxProvider.ForAttributeWithMetadataName(
                    CommonConfigConstants.GenerateAttrFqn,
                    predicate: static (node, _) => node is TypeDeclarationSyntax tds
                                                   && tds.Modifiers.Any(SyntaxKind.PartialKeyword),
                    transform: static (ctx, ct) =>
                    {
                        var syntax = (TypeDeclarationSyntax)ctx.TargetNode;
                        var symbol = ctx.SemanticModel.GetDeclaredSymbol(syntax, ct)! ;
                        return (syntax, symbol);
                    })
                .Where(static pair => pair.symbol is not null);

            context.RegisterSourceOutput(targets, static (spc, pair) =>
            {
                Execute(pair.Symbol, spc);
            });
        }

        private static void Execute(INamedTypeSymbol classSymbol, SourceProductionContext context)
        {
            // if (!DerivesFrom(classSymbol, ScriptableObjectFqn))
            // {
            //     return;
            // }

            string? source = GenerateForClass(classSymbol, context.CancellationToken);
            if (source is null)
            {
                return;
            }

            string hintName = classSymbol.ToDisplayString(SymbolDisplayFormat.FullyQualifiedFormat)
                .Replace("global::", "")
                .Replace('<', '{')
                .Replace('>', '}')
                .Replace(", ", "-")
                + ".Getters.g.cs";

            context.AddSource(hintName, SourceText.From(source, Encoding.UTF8));
        }

        private static string? GenerateForClass(
            INamedTypeSymbol classSymbol,
            CancellationToken ct)
        {
            HashSet<string> existingPublicProperties = GetExistingPublicPropertyNames(classSymbol);

            List<FieldInfo> fields = new();

            foreach (IFieldSymbol field in classSymbol.GetMembers().OfType<IFieldSymbol>())
            {
                ct.ThrowIfCancellationRequested();

                if (field.IsStatic || field.IsConst || field.IsImplicitlyDeclared)
                {
                    continue;
                }

                if (field.DeclaredAccessibility != Accessibility.Private)
                {
                    continue;
                }

                if (HasAttributeByName(field, CommonConfigConstants.SkipAttrFqn))
                {
                    continue;
                }

                string? propName = FieldNameToPropertyName(field.Name);
                if (propName is null)
                {
                    continue;
                }

                if (existingPublicProperties.Contains(propName))
                {
                    continue;
                }

                if (fields.Any(f => f.PropertyName == propName))
                {
                    continue;
                }

                bool isUserStruct = !classSymbol.IsValueType
                                    && field.Type.IsValueType
                                    && field.Type.TypeKind == TypeKind.Struct
                                    && field.Type.SpecialType == SpecialType.None;

                fields.Add(new FieldInfo
                {
                    FieldName = field.Name,
                    PropertyName = propName,
                    TypeFullName = field.Type.ToDisplayString(SymbolDisplayFormat.FullyQualifiedFormat),
                    UseRef = isUserStruct,
                });
            }

            if (fields.Count == 0)
            {
                return null;
            }

            StringBuilder sb = new();
            sb.AppendLine("// <auto-generated/>");
            sb.AppendLine("#pragma warning disable");
            sb.AppendLine();

            string? namespaceName = classSymbol.ContainingNamespace.IsGlobalNamespace
                ? null
                : classSymbol.ContainingNamespace.ToDisplayString();

            if (namespaceName is not null)
            {
                sb.AppendLine($"namespace {namespaceName}");
                sb.AppendLine("{");
            }

            string indent = namespaceName is not null ? "    " : "";

            string accessibility = classSymbol.DeclaredAccessibility switch
            {
                Accessibility.Public => "public",
                Accessibility.Internal => "internal",
                _ => "internal"
            };

            var typeType = classSymbol.IsValueType ? "struct" : "class";
            
            sb.AppendLine($"{indent}{accessibility} partial {typeType} {classSymbol.Name}");
            sb.AppendLine($"{indent}{{");

            for (int i = 0; i < fields.Count; i++)
            {
                if (i > 0)
                {
                    sb.AppendLine();
                }

                FieldInfo f = fields[i];

                if (f.UseRef)
                {
                    sb.AppendLine($"{indent}    public ref {f.TypeFullName} {f.PropertyName}");
                    sb.AppendLine($"{indent}    {{");
                    sb.AppendLine($"{indent}        [System.Runtime.CompilerServices.MethodImpl(System.Runtime.CompilerServices.MethodImplOptions.AggressiveInlining)]");
                    sb.AppendLine($"{indent}        get => ref {f.FieldName};");
                    sb.AppendLine($"{indent}    }}");
                }
                else
                {
                    sb.AppendLine($"{indent}    public {f.TypeFullName} {f.PropertyName}");
                    sb.AppendLine($"{indent}    {{");
                    sb.AppendLine($"{indent}        [System.Runtime.CompilerServices.MethodImpl(System.Runtime.CompilerServices.MethodImplOptions.AggressiveInlining)]");
                    sb.AppendLine($"{indent}        get => {f.FieldName};");
                    sb.AppendLine($"{indent}    }}");
                }
            }

            sb.AppendLine($"{indent}}}");

            if (namespaceName is not null)
            {
                sb.AppendLine("}");
            }

            return sb.ToString();
        }

        // ─── Helpers ──────────────────────────────────────────────────────

        private static string? FieldNameToPropertyName(string fieldName)
        {
            string raw = fieldName;

            if (raw.StartsWith("_"))
            {
                raw = raw.Substring(1);
            }

            if (raw.Length == 0)
            {
                return null;
            }

            return char.ToUpperInvariant(raw[0]) + raw.Substring(1);
        }

        private static bool HasAttributeByName(ISymbol symbol, string attributeFqn)
        {
            foreach (AttributeData attr in symbol.GetAttributes())
            {
                if (attr.AttributeClass is null)
                {
                    continue;
                }

                if (attr.AttributeClass.ToDisplayString() == attributeFqn)
                {
                    return true;
                }
            }

            return false;
        }

        private static bool DerivesFrom(INamedTypeSymbol type, string baseFqn)
        {
            INamedTypeSymbol? current = type.BaseType;
            while (current is not null)
            {
                if (current.ToDisplayString() == baseFqn)
                {
                    return true;
                }

                current = current.BaseType;
            }

            return false;
        }

        private static HashSet<string> GetExistingPublicPropertyNames(INamedTypeSymbol classSymbol)
        {
            HashSet<string> names = new();
            INamedTypeSymbol? current = classSymbol;
            while (current is not null)
            {
                foreach (IPropertySymbol prop in current.GetMembers().OfType<IPropertySymbol>())
                {
                    if (prop.DeclaredAccessibility == Accessibility.Public)
                    {
                        names.Add(prop.Name);
                    }
                }

                current = current.BaseType;
            }

            return names;
        }

        private struct FieldInfo
        {
            public string FieldName;
            public string PropertyName;
            public string TypeFullName;
            public bool UseRef;
        }
    }
}
